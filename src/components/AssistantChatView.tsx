import React, { useState, useRef, useEffect } from 'react';
import {
  MessageSquare,
  Send,
  Sparkles,
  Bot,
  User,
  Download,
  Trash2,
  AlertCircle,
  Loader2,
  FileText,
  BookOpen,
  ArrowRight,
  ShieldAlert,
} from 'lucide-react';
import { useResearch } from '../context/ResearchContext.tsx';
import { downloadAsPdf, downloadAsText } from '../lib/pdfExport.ts';
import type { ChatMessage, ActiveTab, Paper } from '../types/index.ts';

interface AssistantChatViewProps {
  initialPaperId?: string;
  setActiveTab: (tab: ActiveTab) => void;
}

export const AssistantChatView: React.FC<AssistantChatViewProps> = ({
  initialPaperId,
  setActiveTab,
}) => {
  const { papers, saveChatSession } = useResearch();

  const [selectedPaperId, setSelectedPaperId] = useState<string>(
    initialPaperId || (papers.length > 0 ? papers[0].id : '')
  );
  const [inputMessage, setInputMessage] = useState('');
  const [messages, setMessages] = useState<ChatMessage[]>([]);
  const [isLoading, setIsLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const messagesEndRef = useRef<HTMLDivElement>(null);

  const selectedPaper = papers.find((p) => p.id === selectedPaperId) || papers[0];

  // Initialize or reset conversation when paper changes
  useEffect(() => {
    if (selectedPaper) {
      setMessages([
        {
          id: 'welcome_msg',
          role: 'assistant',
          content: `Welcome! I am your Aura Research Assistant for "${selectedPaper.title}". Every answer I provide is strictly grounded in the uploaded paper text, with page references ([Page X]) where evidence exists. If the paper does not contain sufficient evidence to answer, I will explicitly inform you. What would you like to investigate?`,
          timestamp: new Date().toISOString(),
        },
      ]);
    }
  }, [selectedPaperId]);

  useEffect(() => {
    messagesEndRef.current?.scrollIntoView({ behavior: 'smooth' });
  }, [messages]);

  const handleSendMessage = async (textToSend?: string) => {
    const queryText = (textToSend || inputMessage).trim();
    if (!queryText || !selectedPaper) return;

    const userMsg: ChatMessage = {
      id: `msg_${Date.now()}_u`,
      role: 'user',
      content: queryText,
      timestamp: new Date().toISOString(),
    };

    const newMessages = [...messages, userMsg];
    setMessages(newMessages);
    setInputMessage('');
    setError(null);
    setIsLoading(true);

    try {
      const response = await fetch('/api/chat', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          title: selectedPaper.title,
          text: selectedPaper.extractedText,
          messages: newMessages.map((m) => ({
            role: m.role,
            content: m.content,
          })),
        }),
      });

      if (!response.ok) {
        const errJson = await response.json();
        throw new Error(errJson.error || 'Failed to get answer from research assistant.');
      }

      const data = await response.json();

      const assistantMsg: ChatMessage = {
        id: `msg_${Date.now()}_a`,
        role: 'assistant',
        content: data.reply || 'No response generated.',
        timestamp: new Date().toISOString(),
      };

      const finalMessages = [...newMessages, assistantMsg];
      setMessages(finalMessages);

      // Save session to history
      saveChatSession({
        paperId: selectedPaper.id,
        paperTitle: selectedPaper.title,
        messages: finalMessages,
      });
    } catch (err: any) {
      console.error('Chat error:', err);
      setError(err?.message || 'Error communicating with research assistant.');
    } finally {
      setIsLoading(false);
    }
  };

  const clearChat = () => {
    if (selectedPaper) {
      setMessages([
        {
          id: 'welcome_msg',
          role: 'assistant',
          content: `Conversation reset. Ready to answer questions on "${selectedPaper.title}" with evidence-based page citations.`,
          timestamp: new Date().toISOString(),
        },
      ]);
    }
  };

  const handleExportChatPdf = () => {
    if (!selectedPaper) return;
    const sections = messages.map((m) => ({
      heading: `${m.role === 'user' ? 'Researcher Question' : 'Aura Assistant Answer'} (${new Date(
        m.timestamp
      ).toLocaleTimeString()})`,
      body: m.content,
    }));

    downloadAsPdf(
      selectedPaper.title,
      'Research Assistant Inquiry Transcript',
      sections,
      `chat_transcript_${selectedPaper.title.slice(0, 20).toLowerCase().replace(/[^a-z0-9]+/g, '_')}.pdf`
    );
  };

  const handleExportChatTxt = () => {
    if (!selectedPaper) return;
    const textContent = `# Research Inquiry Transcript: ${selectedPaper.title}
Generated by Aura Research Assistant

${messages
  .map(
    (m) =>
      `[${m.role.toUpperCase()}] (${new Date(m.timestamp).toLocaleTimeString()}):\n${m.content}\n`
  )
  .join('\n----------------------------------------\n\n')}
`;
    downloadAsText(
      `chat_transcript_${selectedPaper.title.slice(0, 20).toLowerCase().replace(/[^a-z0-9]+/g, '_')}.txt`,
      textContent
    );
  };

  // Helper to format assistant response with highlighted [Page X] badges
  const renderMessageContent = (content: string) => {
    // Regex for [Page X] or [Section Y]
    const parts = content.split(/(\[Page\s+\d+\]|\[Section\s+[\d\.]+\])/g);

    const isLackOfEvidence =
      content.toLowerCase().includes('does not provide enough evidence') ||
      content.toLowerCase().includes('does not provide sufficient evidence');

    return (
      <div className="space-y-2">
        {isLackOfEvidence && (
          <div className="inline-flex items-center space-x-1.5 px-2.5 py-1 rounded bg-amber-100 text-amber-800 text-[11px] font-semibold mb-2">
            <ShieldAlert className="w-3.5 h-3.5 text-amber-600" />
            <span>Insufficient Evidence in Uploaded Text</span>
          </div>
        )}
        <div className="text-sm leading-relaxed whitespace-pre-wrap font-sans">
          {parts.map((part, index) => {
            if (/^\[Page\s+\d+\]$/.test(part) || /^\[Section\s+[\d\.]+\]$/.test(part)) {
              return (
                <span
                  key={index}
                  className="inline-block bg-blue-100 text-blue-800 font-semibold text-xs px-1.5 py-0.5 rounded mx-1 border border-blue-200"
                >
                  {part}
                </span>
              );
            }
            return <span key={index}>{part}</span>;
          })}
        </div>
      </div>
    );
  };

  if (papers.length === 0) {
    return (
      <div className="max-w-3xl mx-auto bg-white rounded-2xl border border-slate-200 p-8 text-center space-y-4">
        <div className="w-12 h-12 rounded-2xl bg-blue-50 text-blue-600 flex items-center justify-center mx-auto">
          <MessageSquare className="w-6 h-6" />
        </div>
        <h2 className="text-lg font-bold text-slate-900 font-serif">
          No Papers Available for Research Chat
        </h2>
        <p className="text-xs text-slate-500 max-w-md mx-auto">
          Upload a research paper or load a sample paper to query its findings, experimental methodology, and conclusions with page citations.
        </p>
        <button
          onClick={() => setActiveTab('upload')}
          className="px-4 py-2 bg-blue-600 hover:bg-blue-700 text-white text-xs font-semibold rounded-xl shadow-xs"
        >
          Go to Upload Papers
        </button>
      </div>
    );
  }

  const samplePrompts = [
    'What research questions and core hypotheses does this paper investigate?',
    'Explain the experimental methodology, datasets, and baseline models.',
    'What empirical results and performance metrics are reported?',
    'What explicit limitations and constraints did the authors declare?',
  ];

  return (
    <div className="max-w-4xl mx-auto space-y-6">
      {/* Top Header & Paper Selector */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h1 className="text-2xl font-bold text-slate-900 font-serif">
            Research Assistant Chat
          </h1>
          <p className="text-xs sm:text-sm text-slate-500 mt-0.5">
            Ask questions about your uploaded paper and receive evidence-based answers with page citations.
          </p>
        </div>

        {/* Paper Selector Dropdown */}
        <div className="w-full sm:w-80">
          <label className="block text-[11px] font-semibold text-slate-500 uppercase tracking-wider mb-1">
            Current Document Context:
          </label>
          <select
            value={selectedPaperId}
            onChange={(e) => setSelectedPaperId(e.target.value)}
            className="w-full bg-white border border-slate-300 rounded-xl px-3 py-2 text-xs font-medium text-slate-800 shadow-2xs focus:ring-2 focus:ring-blue-500 focus:outline-none truncate"
          >
            {papers.map((p) => (
              <option key={p.id} value={p.id}>
                {p.title} ({p.pageCount} pages)
              </option>
            ))}
          </select>
        </div>
      </div>

      {/* Chat Container */}
      <div className="bg-white rounded-2xl border border-slate-200 shadow-2xs flex flex-col h-[650px] overflow-hidden">
        {/* Chat Header Actions */}
        <div className="p-3.5 border-b border-slate-100 flex items-center justify-between bg-slate-50/50">
          <div className="flex items-center space-x-2 min-w-0">
            <div className="w-7 h-7 rounded-lg bg-blue-600 text-white flex items-center justify-center shrink-0">
              <Bot className="w-4 h-4" />
            </div>
            <div className="min-w-0">
              <h3 className="text-xs font-bold text-slate-900 truncate">
                {selectedPaper?.title}
              </h3>
              <p className="text-[10px] text-slate-400">
                {selectedPaper?.pageCount} Pages • Grounded Evidence Mode
              </p>
            </div>
          </div>

          <div className="flex items-center space-x-1.5 shrink-0">
            <button
              onClick={handleExportChatPdf}
              title="Download Transcript as PDF"
              className="p-1.5 rounded-lg text-slate-500 hover:text-blue-600 hover:bg-blue-50 text-xs font-medium inline-flex items-center space-x-1 transition-colors"
            >
              <Download className="w-3.5 h-3.5" />
              <span className="hidden sm:inline text-xs">PDF</span>
            </button>
            <button
              onClick={handleExportChatTxt}
              title="Download Transcript as TXT"
              className="p-1.5 rounded-lg text-slate-500 hover:text-blue-600 hover:bg-blue-50 text-xs font-medium inline-flex items-center space-x-1 transition-colors"
            >
              <span className="text-xs">TXT</span>
            </button>
            <button
              onClick={clearChat}
              title="Clear Conversation"
              className="p-1.5 rounded-lg text-slate-400 hover:text-red-600 hover:bg-red-50 transition-colors"
            >
              <Trash2 className="w-3.5 h-3.5" />
            </button>
          </div>
        </div>

        {/* Message Thread */}
        <div className="flex-1 overflow-y-auto p-4 sm:p-6 space-y-4 bg-slate-50/20">
          {messages.map((msg) => {
            const isUser = msg.role === 'user';
            return (
              <div
                key={msg.id}
                className={`flex items-start space-x-3 ${isUser ? 'flex-row-reverse space-x-reverse' : ''}`}
              >
                <div
                  className={`w-8 h-8 rounded-xl flex items-center justify-center shrink-0 text-xs ${
                    isUser
                      ? 'bg-blue-600 text-white shadow-xs'
                      : 'bg-white text-blue-700 border border-slate-200 shadow-2xs'
                  }`}
                >
                  {isUser ? <User className="w-4 h-4" /> : <Bot className="w-4 h-4" />}
                </div>

                <div
                  className={`max-w-[85%] rounded-2xl p-4 shadow-2xs ${
                    isUser
                      ? 'bg-blue-600 text-white'
                      : 'bg-white text-slate-800 border border-slate-200'
                  }`}
                >
                  {isUser ? (
                    <p className="text-sm leading-relaxed whitespace-pre-wrap">{msg.content}</p>
                  ) : (
                    renderMessageContent(msg.content)
                  )}
                  <div
                    className={`text-[10px] mt-1.5 text-right ${
                      isUser ? 'text-blue-100' : 'text-slate-400'
                    }`}
                  >
                    {new Date(msg.timestamp).toLocaleTimeString([], {
                      hour: '2-digit',
                      minute: '2-digit',
                    })}
                  </div>
                </div>
              </div>
            );
          })}

          {isLoading && (
            <div className="flex items-start space-x-3">
              <div className="w-8 h-8 rounded-xl bg-white text-blue-700 border border-slate-200 flex items-center justify-center">
                <Bot className="w-4 h-4" />
              </div>
              <div className="bg-white border border-slate-200 rounded-2xl p-4 text-xs text-slate-600 flex items-center space-x-2">
                <Loader2 className="w-4 h-4 animate-spin text-blue-600" />
                <span>Searching paper pages and verifying citations...</span>
              </div>
            </div>
          )}

          <div ref={messagesEndRef} />
        </div>

        {/* Quick Suggestion Chips */}
        <div className="p-2.5 bg-slate-50 border-t border-slate-200/80 overflow-x-auto flex items-center space-x-2 shrink-0">
          <span className="text-[10px] font-bold uppercase text-slate-400 shrink-0 pl-1">
            Prompt Ideas:
          </span>
          {samplePrompts.map((p, idx) => (
            <button
              key={idx}
              onClick={() => handleSendMessage(p)}
              disabled={isLoading}
              className="text-[11px] whitespace-nowrap bg-white hover:bg-blue-50 text-slate-600 hover:text-blue-700 px-2.5 py-1 rounded-lg border border-slate-200 transition-colors shrink-0"
            >
              {p}
            </button>
          ))}
        </div>

        {/* Input Bar */}
        <div className="p-3 bg-white border-t border-slate-200">
          {error && (
            <div className="mb-2 p-2 bg-red-50 border border-red-200 text-red-700 text-xs rounded-lg flex items-center space-x-2">
              <AlertCircle className="w-3.5 h-3.5 shrink-0" />
              <span>{error}</span>
            </div>
          )}

          <form
            onSubmit={(e) => {
              e.preventDefault();
              handleSendMessage();
            }}
            className="flex items-center space-x-2"
          >
            <input
              type="text"
              placeholder={`Ask a question grounded in "${selectedPaper?.title || 'the paper'}"...`}
              value={inputMessage}
              onChange={(e) => setInputMessage(e.target.value)}
              disabled={isLoading}
              className="flex-1 bg-slate-50 border border-slate-300 rounded-xl px-4 py-2.5 text-xs sm:text-sm text-slate-800 placeholder-slate-400 focus:bg-white focus:ring-2 focus:ring-blue-500 focus:outline-none"
            />
            <button
              type="submit"
              disabled={isLoading || !inputMessage.trim()}
              className="px-4 py-2.5 bg-blue-600 hover:bg-blue-700 disabled:bg-slate-300 text-white rounded-xl text-xs sm:text-sm font-semibold transition-all shadow-xs flex items-center space-x-1.5 shrink-0"
            >
              <span>Ask</span>
              <Send className="w-3.5 h-3.5" />
            </button>
          </form>
        </div>
      </div>
    </div>
  );
};
